export type TranslationKey = keyof typeof dictionary;

export function translate(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
    return dictionary[key][locale === "en" ? 1 : 0].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function translateText(locale: Locale, text: string): string {
    return Object.hasOwn(dictionary, text) ? translate(locale, text as TranslationKey) : text;
}
